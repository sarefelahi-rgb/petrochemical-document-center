// چیدمان خودکار شبکه‌ای برای مناطق/تجهیزات — ردیفی با حداکثر ۳ ستون، وسط‌چین
export function gridPos(i: number, n: number, bw: number, bh: number, y0 = 80): { x: number; y: number } {
  const cols = Math.max(1, Math.min(n, 3));
  const gapX = 55, gapY = 70;
  const row = Math.floor(i / cols);
  const col = i % cols;
  const rows = Math.ceil(n / cols);
  const totalW = cols * bw + (cols - 1) * gapX;
  const x0 = (MAP_VIEWBOX.w - totalW) / 2;
  return {
    x: Math.round(x0 + col * (bw + gapX)),
    y: Math.round(Math.max(40, y0 + row * (bh + gapY) - (rows > 1 ? 20 : 0))),
  };
}

