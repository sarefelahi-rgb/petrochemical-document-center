// ساخت فهرست تختِ گره‌ها به ترتیب والد-اول — برای بذرکاری جدول MapNode
export function buildSeedMapNodes(): SeedNode[] {
  const nodes: SeedNode[] = [];
  for (const u of UNIT_LAYOUT) {
    nodes.push({ key: u.key, kind: 'UNIT', code: u.code, name: u.name, desc: u.desc, x: u.x, y: u.y, w: u.w, h: u.h, color: u.color });
    const areas = AREA_LAYOUT[u.key] || [];
    areas.forEach(([akey, aname, adesc], ai) => {
      const p = gridPos(ai, areas.length, 260, 120);
      nodes.push({ key: akey, parentKey: u.key, kind: 'AREA', name: aname, desc: adesc, x: p.x, y: p.y, w: 260, h: 120, color: u.color });
      const eqs = EQUIPMENT_LAYOUT[akey] || [];
      eqs.forEach(([tag, ename, ekind], ei) => {
        const ep = gridPos(ei, eqs.length, 230, 110);
        nodes.push({ key: `${akey}::${tag}`, parentKey: akey, kind: 'EQUIPMENT', code: tag, name: ename, desc: ekind, x: ep.x, y: ep.y, w: 230, h: 110, color: 'primary' });
      });
    });
  }
  return nodes;
}

